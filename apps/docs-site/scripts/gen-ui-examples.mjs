// Writes components/ui-docs/examples.gen.tsx: every Beam UI example and Do/Don't file, keyed "button/default"
// or "stat-card/dont", so docs pages render the same files the registry ships.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../packages/ui/registry/components", import.meta.url));
const out = fileURLToPath(new URL("../components/ui-docs/examples.gen.tsx", import.meta.url));
const entries = [];
for (const component of readdirSync(root).sort()) {
  for (const folder of ["examples", "do-dont"]) {
    const dir = join(root, component, folder);
    if (!existsSync(dir)) continue;
    for (const file of readdirSync(dir).filter((f) => f.endsWith(".tsx")).sort()) {
      const name = file.replace(/\.tsx$/, "");
      entries.push({ key: `${component}/${name}`, path: `@beam/ui/registry/components/${component}/${folder}/${file}`, file: `${component}/${folder}/${file}` });
    }
  }
}
const id = (i) => `E${i}`;
const lines = [
  "// Generated by scripts/gen-ui-examples.mjs. Do not edit.",
  'import type { ComponentType } from "react";',
  ...entries.map((e, i) => `import ${id(i)} from "${e.path}";`),
  "",
  "export const EXAMPLES: Record<string, { Component: ComponentType; file: string }> = {",
  ...entries.map((e, i) => `  "${e.key}": { Component: ${id(i)}, file: "${e.file}" },`),
  "};",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`ui examples: ${entries.length}`);
